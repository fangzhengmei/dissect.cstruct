def canonical(value: Any, depth: int = 0) -> Any:
    """Return a comparable representation of a parsed value, independent of its concrete class.

    The two paths legitimately return different Python classes for the same evidence (``uint8`` vs
    ``int``, ``char[n]`` vs ``bytes``). Comparison must normalize the class while preserving field
    names, enum members, union proxies and sizes.
    """
    if depth > 10:
        return ("<deep>",)
    if isinstance(value, UnionProxy):
        return ("union-proxy", value.__attr__, canonical(value.__target__, depth + 1))
    if isinstance(value, Void):
        return ("void",)
    if isinstance(value, dict):
        return ("dict", tuple(sorted((key, canonical(val, depth + 1)) for key, val in value.items())))
    if hasattr(value, "__dict__") and hasattr(value.__class__, "__fields__"):
        return ("structure", tuple((key, canonical(val, depth + 1)) for key, val in value.__dict__.items()))
    if isinstance(value, list):
        return ("list", tuple(canonical(item, depth + 1) for item in value))
    if isinstance(value, (bytes, bytearray, memoryview)):
        return ("bytes", memoryview(value).tobytes())
    if isinstance(value, str):
        # ``wchar[n]`` is a ``str`` subclass; normalize so it compares to a plain ``str``
        return ("str", str(value))
    if isinstance(value, Enum):
        return ("enum", type(value).__name__, value.name, int(value.value))
    if isinstance(value, float):
        return ("float", "nan") if math.isnan(value) else ("float", value)
    if isinstance(value, bool):
        return ("int", int(value))
    if isinstance(value, int):
        return ("int", int(value))
    return ("other", type(value).__name__, repr(value))


def same(left: Any, right: Any) -> bool:
    """Compare canonical values, treating NaN as equal to NaN."""
    if isinstance(left, (tuple, list)) and isinstance(right, (tuple, list)):
        return len(left) == len(right) and all(same(lval, rval) for lval, rval in zip(left, right, strict=False))
    if isinstance(left, float) and isinstance(right, float):
        return (math.isnan(left) and math.isnan(right)) or left == right
    if type(left) is not type(right):
        return False
    return left == right


@dataclass(frozen=True)
class Observation:
    """Everything a caller can observe about one read attempt."""

    path: str
    start: int
    position: int
    value: Any = None
    dumps: Any = None
    dynamic_sizes: Any = None
    error: str | None = None
    message: str | None = None

    @property
    def consumed(self) -> int:
        return self.position - self.start

    @property
    def ok(self) -> bool:
        return self.error is None

    def __str__(self) -> str:
        if self.ok:
            return f"<{self.path} ok consumed={self.consumed} value={self.value!r}>"
        return f"<{self.path} {self.error} consumed={self.consumed} pos={self.position} message={self.message!r}>"


def observe(type_: type[Structure], stream: Any, path: str, endian: str) -> Observation:
    """Read one structure from the stream and capture every observable property."""
    start = stream.tell()

    try:
        obj = type_._read(stream, context=None, endian=endian)
    except Exception as e:
        return Observation(path, start, stream.tell(), error=type(e).__name__, message=str(e))

    try:
        dumps: Any = obj.dumps()
    except Exception as e:
        dumps = ("dump-error", type(e).__name__, str(e))

    return Observation(
        path,
        start,
        stream.tell(),
        value=canonical(obj),
        dumps=dumps,
        dynamic_sizes=canonical(getattr(obj, "__dynamic_sizes__", {})),
    )


def divergences(left: Observation, right: Observation) -> tuple[str, ...]:
    """Return the sorted aspects in which two read attempts differ."""
    aspects = []
    if left.ok != right.ok:
        aspects.append("status")
    if left.ok and right.ok:
        if not same(left.value, right.value):
            aspects.append("value")
        if left.consumed != right.consumed:
            aspects.append("consumed")
        if left.dumps != right.dumps:
            aspects.append("dumps")
        if not same(left.dynamic_sizes, right.dynamic_sizes):
            aspects.append("dynamic_sizes")
    elif not left.ok and not right.ok:
        if left.error != right.error:
            aspects.append("exception_type")
        if left.position != right.position:
            aspects.append("position")
        if left.message != right.message:
            aspects.append("message")
    return tuple(sorted(aspects))


