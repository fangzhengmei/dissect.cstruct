def load_pair_uncached(case: Case) -> tuple[cstruct, cstruct]:
    """Load the definition into an independent interpreted and compiled instance."""
    interpreted = cstruct(endian=case.endian).load(case.definition, compiled=False, align=case.align)
    compiled = cstruct(endian=case.endian).load(case.definition, compiled=True, align=case.align)

    if case.offset_field:
        # Add the same explicit offset field to both instances
        interpreted.test.add_field("extra", interpreted.uint32, offset=8)
        compiled.test.add_field("extra", compiled.uint32, offset=8)

    assert not interpreted.test.__compiled__
    assert compiled.test.__compiled__
    return interpreted, compiled


@cache
def load_pair(case: Case) -> tuple[cstruct, cstruct]:
    """Cached pair for sample execution; reading never mutates the loaded type classes."""
    return load_pair_uncached(case)


def seekable(factory: Callable[[bytes], Any]) -> bool:
    try:
        return bool(factory(b"").seekable())
    except Exception:
        return False


def run_sample(case: Case, sample: Sample, factory: Callable[[bytes], Any]) -> tuple[Observation, Observation] | None:
    """Read the sample through both paths from identical, freshly created streams."""
    if sample.start and not seekable(factory):
        return None

    interpreted, compiled = load_pair(case)

    streams = []
    for _ in range(2):
        stream = factory(sample.data)
        if sample.start:
            stream.seek(sample.start)
        streams.append(stream)

    return (
        observe(interpreted.test, streams[0], "interpreted", case.endian),
        observe(compiled.test, streams[1], "compiled", case.endian),
    )


@dataclass
class Finding:
    """A single sample on which the two paths differ."""

    case: str
    sample: Sample
    stream: str
    aspects: tuple[str, ...]
    left: Observation
    right: Observation

    @property
    def key(self) -> tuple[str, str, str]:
        return (self.case, STREAM_FAMILY[self.stream], self.sample.category)

    @property
    def cosmetic(self) -> bool:
        return frozenset(self.aspects) <= COSMETIC_ASPECTS

    def __str__(self) -> str:
        return (
            f"{self.case} / {self.sample.id} / {self.stream}: {self.aspects}\n"
            f"    data={self.sample.data.hex()} start={self.sample.start}\n"
            f"    interpreted: {self.left}\n"
            f"    compiled:    {self.right}"
        )


def findings_for(case: Case, stream_id: str, samples: Iterable[Sample] | None = None) -> list[Finding]:
    """Collect all differing samples for one case on one stream."""
    factory = STREAM_FACTORIES[stream_id]
    findings = []

    for sample in samples if samples is not None else case.samples:
        result = run_sample(case, sample, factory)
        if result is None:
            continue

        left, right = result
        aspects = divergences(left, right)
        if aspects:
            findings.append(Finding(case.name, sample, stream_id, aspects, left, right))

    return findings


# A message-only difference is always the packed block reporting a different expected size
MESSAGE_ONLY_CAUSE = "D1-block-eof"


def defects_for(findings: list[Finding]) -> tuple[str, ...]:
    """Return the documented root causes that apply to these findings.

    A difference that only changes the human readable EOF size is always the packed block reading
    more than the single field would, so it is attributed to ``D1`` directly. Anything else uses the
    causes recorded for the case, which is a superset of the signatures seen for it.
    """
    found = []
    for case in sorted({finding.case for finding in findings}):
        if all(finding.aspects == ("message",) for finding in findings if finding.case == case):
            found.append(MESSAGE_ONLY_CAUSE)
        else:
            found.extend(CASE_DEFECTS.get(case, ()))
    return tuple(dict.fromkeys(found))


def describe(findings: list[Finding]) -> str:
    return "\n".join(f"  - {finding}" for finding in findings)


def guard(findings: list[Finding], *, severity: str) -> set[str]:
    """Fail on undocumented signatures, accept message-only ones, and record defects as expected failures.

    Returns the ids of samples whose only difference is the EOF message, so a caller that additionally
    requires a successful parse can skip exactly those samples instead of failing on them.
    """
    cosmetic = []
    defects = []
    undocumented = []

    for finding in findings:
        expected = DIVERGENCE_INVENTORY.get(finding.key, {})
        if finding.aspects not in expected:
            undocumented.append(finding)
        elif finding.cosmetic:
            cosmetic.append(finding)
        else:
            defects.append(finding)

    assert not undocumented, (
        "Observed divergence signatures that are not in DIVERGENCE_INVENTORY. "
        "Either the read paths changed or the catalogue is stale:\n"
        + describe(undocumented)
        + "\nObserved keys:\n"
        + "\n".join(f"  {finding.key}: {finding.aspects}" for finding in undocumented)
    )

    # A cosmetic difference may only ever be the human readable size in an EOF message
    for finding in cosmetic:
        assert not finding.left.ok
        assert not finding.right.ok
        assert finding.left.error == finding.right.error
        assert finding.left.position == finding.right.position
        assert finding.left.error == "EOFError"
        assert EOF_MESSAGE.match(finding.left.message or "")
        assert EOF_MESSAGE.match(finding.right.message or "")

    if defects:
        causes = defects_for(defects)
        assert causes, (
            "a divergence was recorded for a case without a documented root cause, so the failure is not "
            "explainable yet; add the case to CASE_DEFECTS after identifying the cause:\n" + describe(defects)
        )
        detail = "\n".join(f"  {cause}: {DEFECTS[cause]}\n    hint: {DEFECT_HINTS[cause]}" for cause in causes)
        pytest.xfail(
            f"{severity}: {len(defects)} sample(s) parse differently between the compiled and "
            f"interpreted paths. Known root causes:\n{detail}\nFindings:\n{describe(defects)}"
        )

    return {finding.sample.id for finding in cosmetic}


