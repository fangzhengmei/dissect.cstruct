"""Security differential tests for the compiled and interpreted read paths.

A structure can be read through two independent implementations: the interpreted
``StructureMetaType._read`` and the code generated by ``compiler._ReadSourceGenerator``.
Forensic parsing is only trustworthy when both paths agree on three properties for the same bytes:

* the parsed evidence (field values, dynamic sizes, and the bytes a re-serialization produces),
* the number of bytes consumed (the boundary of the record and of everything after it),
* the failure boundary (exception class, message, and the stream position left behind).

Every sample in this module is fed to both paths and those properties are compared. Legal samples
must agree exactly. Adversarial samples (length overrides, truncations, embedded records, short
reads, non-seekable streams) must be rejected at the same boundary, so a following record is never
read from a shifted offset.

Anything that does not line up is a finding. The findings that this test suite currently discovers
are recorded in :data:`DIVERGENCE_INVENTORY`, keyed by ``(case, stream family, sample category)``
and mapped to the exact set of differing aspects with their observation counts. This is a golden
baseline, not a permission slip:

* an observed aspect signature that is not in the inventory fails the test with the key to update,
* an inventory entry that is no longer observed with the same count fails
  :func:`test_inventory_is_current`, so fixing a defect cannot silently pass either,
* every non-message entry needs a root cause in :data:`DEFECTS` and a corpus in
  :data:`CASE_DEFECTS`, so a failure always names a mechanism and not just a signature,
* only the ``message`` aspect is treated as cosmetic, and only after the two paths are shown to fail
  with the same exception class at the same stream position; it never excuses a different evidence
  value, a different consumed length or a different failure position,
* :func:`test_harness_detects_evidence_and_boundary_drift` injects a deliberate drift to prove the
  comparison is not vacuous, so passing tests say more than "nothing crashed".
"""

