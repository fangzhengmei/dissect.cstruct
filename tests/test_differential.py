def _outcome(cs: cstruct, sample_data: bytes, factory: Callable[[bytes], Any], start: int) -> Any:
    """Run one read and return ``(status, position, dumps or message)``."""
    stream = factory(sample_data)
    if start:
        stream.seek(start)
    try:
        obj = cs.test._read(stream, endian="<")
    except Exception as e:
        return (type(e).__name__, stream.tell(), str(e))
    return ("ok", stream.tell(), obj.dumps())


@pytest.mark.parametrize("defect", sorted(DEFECT_REPROS))
def test_known_defect_reproduces_exactly(defect: str) -> None:
    """Each documented defect must still reproduce with the documented inputs and outputs."""
    spec = DEFECT_REPROS[defect]
    stream_id = spec.get("stream", "seekable")
    factory = STREAM_FACTORIES[stream_id]
    align = spec.get("align", False)
    start = spec.get("start", 0)
    offset_field = spec.get("offset_field", False)

    outcomes = []
    for compiled in (False, True):
        cs = cstruct().load(spec["definition"], compiled=compiled, align=align)
        if offset_field:
            cs.test.add_field("extra", cs.uint32, offset=8)
        outcomes.append(_outcome(cs, spec["data"], factory, start))

    assert outcomes == spec["expected"], (
        f"{defect} no longer reproduces as documented.\n"
        f"  recorded: {spec['expected']}\n"
        f"  observed: {outcomes}\n"
        "If the read paths were fixed, remove the defect from DIVERGENCE_INVENTORY, CASE_DEFECTS and DEFECTS."
    )

    # The reproduction must still be a real difference, and it must be a described defect
    assert outcomes[0] != outcomes[1]
    assert defect in DEFECTS
    assert defect in DEFECT_HINTS


# ---------------------------------------------------------------------------------------------
# Generated definitions: deterministic grammar fuzz over lengths, nesting, arrays and unions
# ---------------------------------------------------------------------------------------------

SCALARS = ("uint8", "int8", "uint16", "int16", "uint32", "uint64", "char", "wchar", "uint24", "float", "double")


def generate_definition(rng: random.Random, depth: int = 0) -> str:
    """Generate a structurally valid definition that mixes lengths, nesting, arrays and unions."""
    fields = []
    previous_length = None

    for index in range(rng.randint(1, 6)):
        kind = rng.choices(
            ("scalar", "scalar_array", "dynamic_array", "nested", "union", "bits", "void", "null_terminated"),
            weights=(28, 15, 22, 12, 10, 6, 2, 5),
        )[0]
        name = f"f{index}"

        if kind == "scalar":
            fields.append(f"{rng.choice(SCALARS)} {name};")
        elif kind == "scalar_array":
            element = rng.choice(("uint8", "uint16", "uint32", "char", "wchar", "int16"))
            fields.append(f"{element} {name}[{rng.randint(1, 4)}];")
        elif kind == "dynamic_array":
            element = rng.choice(("uint8", "uint16", "char", "uint32", "wchar"))
            if previous_length and rng.random() < 0.5:
                fields.append(f"{element} {name}[{previous_length}];")
            else:
                fields.append(f"{element} {name}[n];")
                fields.insert(0, "uint8 n;")
                previous_length = "n"
        elif kind == "null_terminated":
            fields.append(f"{rng.choice(('char', 'uint8'))} {name}[];")
        elif kind == "nested":
            if depth < 2:
                fields.append(f"struct {{ {generate_definition(rng, depth + 1)} }} {name};")
        elif kind == "union":
            if depth < 2:
                left = rng.choice(("uint32", "uint16", "uint8[4]", "char[4]"))
                right = rng.choice(("uint16", "uint32", "char[2]", "uint8"))
                fields.append(f"union {{ {left} ua; {right} ub; }} {name};")
        elif kind == "bits":
            fields.append("uint16 b1:3; uint16 b2:5; uint8 b3:4; uint8 b4:4;")
        elif kind == "void":
            fields.append("void;")

    return " ".join(fields)


def generated_inputs(rng: random.Random) -> Iterator[bytes]:
    """Yield random inputs, mutations that target length fields, and truncations."""
    for size in range(32):
        base = bytes(rng.randrange(256) for _ in range(size))
        yield base

        if size:
            mutated = bytearray(base)
            mutated[rng.randrange(size)] = rng.choice((0, 1, 2, 3, 0xFF))
            yield bytes(mutated)


@pytest.mark.parametrize("seed", range(4))
def test_generated_definitions(seed: int) -> None:
    """Generated definitions must not trigger parser defects or silent evidence drift."""
    rng = random.Random(seed)
    accepted = 0

    for _ in range(40):
        definition = f"struct test {{ {generate_definition(rng)} }};"
        try:
            interpreted = cstruct().load(definition, compiled=False)
            compiled = cstruct().load(definition, compiled=True)
        except Exception:
            # Definitions rejected by the parser are out of scope for this differential test
            continue

        assert not interpreted.test.__compiled__
        assert compiled.test.__compiled__

        for data in generated_inputs(rng):
            left = observe(interpreted.test, io.BytesIO(data), "interpreted", "<")
            right = observe(compiled.test, io.BytesIO(data), "compiled", "<")
            aspects = divergences(left, right)

            for observation in (left, right):
                assert observation.error not in INTERNAL_ERRORS, (
                    f"seed={seed} definition={definition!r} data={data.hex()}: "
                    f"input triggered an internal parser error: {observation}"
                )

            if aspects and frozenset(aspects) <= COSMETIC_ASPECTS:
                # Only the human readable size of the packed block differs
                assert left.error == right.error == "EOFError"
                assert left.position == right.position
                accepted += 1
                continue

            assert not aspects, (
                f"seed={seed} definition={definition!r} data={data.hex()} differs in {aspects}:\n"
                f"  interpreted: {left}\n"
                f"  compiled:    {right}"
            )

            if left.ok and right.ok:
                assert same(left.value, right.value)
                assert left.dumps == right.dumps
                assert same(left.dynamic_sizes, right.dynamic_sizes)
            else:
                assert left.error == right.error
                assert left.position == right.position
                assert left.error in PROTOCOL_ERRORS

    # Keep the acceptance count bounded, so a new class of message-only differences is visible
    assert accepted < 400, f"too many generated inputs only differ in the EOF message ({accepted})"
