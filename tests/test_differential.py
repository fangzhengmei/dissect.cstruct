@dataclass(frozen=True)
class Sample:
    """One crafted input, optionally read from a non-zero stream offset."""

    id: str
    data: bytes
    start: int = 0
    legal: bool = False

    @property
    def category(self) -> str:
        return self.id.split("/")[0]


@dataclass(frozen=True)
class Case:
    """A definition and its corpus of samples."""

    name: str
    definition: str
    samples: tuple[Sample, ...]
    align: bool = False
    endian: str = "<"
    offset_field: bool = False


def u8(value: int) -> bytes:
    return struct.pack("<B", value & 0xFF)


def u16(value: int, endian: str = "<") -> bytes:
    return struct.pack(f"{endian}H", value & 0xFFFF)


def u32(value: int, endian: str = "<") -> bytes:
    return struct.pack(f"{endian}I", value & 0xFFFFFFFF)


def truncations(
    base: bytes, starts: tuple[int, ...] = (0,), prefix: str = "truncate", suffix: bytes = b""
) -> list[Sample]:
    """Truncate the base at every byte boundary, optionally followed by the marker record."""
    out = []
    for start in starts:
        for size in range(len(base) + 1):
            label = f"{prefix}/{size}" + (f"/start={start}" if start else "")
            out.append(Sample(label, base[:size] + suffix, start, legal=False))
    return out


def boundary_mutations(
    base: bytes, offset: int, size: int, values: tuple[int, ...], label: str, starts: tuple[int, ...] = (0,)
) -> list[Sample]:
    """Overwrite a length field with structured values: zero, exact, one too many, maximum."""
    out = []
    for start in starts:
        for value in values:
            mutated = bytearray(base)
            mutated[offset : offset + size] = value.to_bytes(size, "little")
            sample_id = f"mutate/{label}@{offset}={value:#x}" + (f"/start={start}" if start else "")
            out.append(Sample(sample_id, bytes(mutated), start, legal=False))
    return out


def with_next(base: bytes, label: str) -> Sample:
    return Sample(f"legal/{label}/next", base + NEXT_RECORD, 0, legal=True)


# -- sample corpora ----------------------------------------------------------------------------


def samples_len_char() -> tuple[Sample, ...]:
    """A length field that selects a char array, followed by a fixed trailer."""
    samples = []
    for count in range(7):
        base = u8(count) + bytes(range(0x41, 0x41 + count)) + struct.pack("<H", 0xBEEF)
        samples.append(Sample(f"legal/count={count}", base, legal=True))
        samples.append(with_next(base, f"count={count}"))

    base = u8(3) + b"ABC" + struct.pack("<H", 0xBEEF)
    samples += boundary_mutations(base, 0, 1, (0, 1, 2, 3, 4, 5, 0x7F, 0xFF), "count", starts=(0, 1, 3, 7))
    samples += truncations(base)
    samples += truncations(base, prefix="recover", suffix=NEXT_RECORD)
    return tuple(samples)


def samples_len_u16() -> tuple[Sample, ...]:
    """A length field that selects an array of multi-byte integers."""
    samples = []
    for count in range(5):
        base = u8(count) + b"".join(u16(0x1000 + i) for i in range(count)) + u32(0xDEADBEEF)
        samples.append(Sample(f"legal/count={count}", base, legal=True))
        samples.append(with_next(base, f"count={count}"))

    base = u8(4) + b"".join(u16(0x2000 + i) for i in range(4)) + u32(0xDEADBEEF)
    samples += boundary_mutations(base, 0, 1, (0, 1, 3, 4, 5, 6, 9, 0xFF), "count", starts=(0, 1, 2, 7))
    samples += truncations(base)
    samples += truncations(base, prefix="recover", suffix=NEXT_RECORD)
    return tuple(samples)


def samples_len_nested_records() -> tuple[Sample, ...]:
    """A length field that selects an array of nested structures."""
    samples = []

    def build(count: int) -> bytes:
        records = b"".join(struct.pack("<HB", 0x8000 + i, 0x40 + i) for i in range(count))
        return u8(count) + records + struct.pack("<H", 0xCAFE)

    for count in range(5):
        base = build(count)
        samples.append(Sample(f"legal/count={count}", base, legal=True))
        samples.append(with_next(base, f"count={count}"))

    base = build(3)
    samples += boundary_mutations(base, 0, 1, (0, 1, 2, 3, 4, 5, 6, 0xFF), "count", starts=(0, 1, 3, 5))
    # Truncations land in the middle of nested records, with and without a following record
    samples += truncations(base)
    samples += truncations(base, prefix="recover", suffix=NEXT_RECORD)
    return tuple(samples)


