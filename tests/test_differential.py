class PipeStream:
    """A non-seekable stream, like a pipe or a socket.

    ``tell()`` works, ``seek()`` raises and ``read(size)`` may return fewer bytes than requested.
    """

    def __init__(self, data: bytes, chunk: int | None = None):
        self._data = data
        self._pos = 0
        self._chunk = chunk

    def read(self, size: int = -1) -> bytes:
        if size is None or size < 0:
            size = len(self._data) - self._pos
        if self._chunk is not None:
            size = min(size, self._chunk)
        data = self._data[self._pos : self._pos + size]
        self._pos += len(data)
        return data

    def tell(self) -> int:
        return self._pos

    def seekable(self) -> bool:
        return False

    def seek(self, *_: Any) -> int:
        raise OSError(29, "Illegal seek")


class ShortReadStream(io.BytesIO):
    """A seekable stream that returns at most ``chunk`` bytes per read, which the IO contract allows."""

    def __init__(self, data: bytes, chunk: int = 1):
        super().__init__(data)
        self.chunk = chunk

    def read(self, size: int = -1) -> bytes:
        if size is None or size < 0:
            size = io.DEFAULT_BUFFER_SIZE
        return super().read(min(size, self.chunk))


