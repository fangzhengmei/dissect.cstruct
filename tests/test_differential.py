@pytest.mark.parametrize("case", CASES)
@pytest.mark.parametrize("stream_id", STREAM_IDS)
def test_legal_samples_agree(case: Case, stream_id: str) -> None:
    """Legal input must yield the same evidence and consume the same bytes through both paths."""
    legal = [sample for sample in case.samples if sample.legal]
    assert legal, "every case must have legal samples"

    findings = findings_for(case, stream_id, legal)
    message_only = guard(findings, severity="legal input")

    # Reachable only when no evidence-affecting divergence was found; assert the full contract
    for sample in legal:
        if sample.id in message_only:
            # Already validated by guard(): both paths reject with the same EOFError at the same
            # position, only the reported size differs
            assert stream_id not in FULL_PARSE_STREAMS
            continue

        result = run_sample(case, sample, STREAM_FACTORIES[stream_id])
        if result is None:
            # The stream cannot be positioned at the sample offset; covered by the seekable streams
            continue
        left, right = result

        if stream_id in FULL_PARSE_STREAMS:
            # A complete seekable stream must parse every legal sample through both paths
            assert left.ok, f"legal sample rejected by the interpreted path: {case.name} / {sample.id}: {left}"
            assert right.ok, f"legal sample rejected by the compiled path: {case.name} / {sample.id}: {right}"
        else:
            # A partial read is a shared limitation, so only identical behaviour is required
            assert left.ok == right.ok, (
                f"legal sample handled differently on a partial-read stream: {case.name} / {sample.id} / "
                f"{stream_id}:\n  interpreted: {left}\n  compiled: {right}"
            )

        if left.ok:
            assert same(left.value, right.value), f"{case.name} / {sample.id}: different evidence values"
            assert left.position == right.position, f"{case.name} / {sample.id}: different consumed lengths"
            assert left.dumps == right.dumps, f"{case.name} / {sample.id}: different re-serialized bytes"
            assert same(left.dynamic_sizes, right.dynamic_sizes)


@pytest.mark.parametrize("case", CASES)
@pytest.mark.parametrize("stream_id", STREAM_IDS)
def test_adversarial_samples_are_handled_explainably(case: Case, stream_id: str) -> None:
    """Hostile input must be rejected at the same boundary, or accepted with identical evidence.

    A hostile sample does not have to be rejected: a length field may still describe a shorter but
    perfectly well-formed record. It must never be *misread* though. So for every hostile sample the
    two paths must either reject it identically (same exception class, same stream position, a
    message that follows the EOF protocol) or accept it and produce byte-identical evidence.
    """
    adversarial = [sample for sample in case.samples if not sample.legal]
    if not adversarial:
        pytest.skip("this case has a purely legal corpus")

    findings = findings_for(case, stream_id, adversarial)
    guard(findings, severity="adversarial input")

    for sample in adversarial:
        result = run_sample(case, sample, STREAM_FACTORIES[stream_id])
        if result is None:
            # The stream cannot be positioned at the sample offset; covered by the seekable streams
            continue
        left, right = result

        for observation in (left, right):
            assert observation.error not in INTERNAL_ERRORS, (
                f"input triggered an internal parser error instead of a protocol rejection: "
                f"{case.name} / {sample.id} / {stream_id}: {observation}"
            )
            if not observation.ok:
                assert observation.error in PROTOCOL_ERRORS, (
                    f"rejection is not explainable by the input: {case.name} / {sample.id} / {stream_id}: {observation}"
                )
                # A failure position may never rewind behind the start of the read
                assert observation.position >= sample.start, (
                    f"failure position before the start of the read: {case.name} / {sample.id} / "
                    f"{stream_id}: {observation}"
                )
                # On a complete stream an EOF can only be detected at the end of the data, so a
                # truncation always consumes the remaining input and the next record cannot be read
                # from a silently shifted offset
                if observation.error == "EOFError" and stream_id in FULL_PARSE_STREAMS:
                    assert observation.position == max(len(sample.data), sample.start), (
                        f"EOFError before the end of the input: {case.name} / {sample.id} / {stream_id}: {observation}"
                    )

        if left.ok or right.ok:
            # Both accepted, otherwise guard() would have recorded the status difference
            assert left.ok, (
                f"one path rejected while the other accepted: {case.name} / {sample.id} / {stream_id}:\n"
                f"  interpreted: {left}\n  compiled: {right}"
            )
            assert right.ok, (
                f"one path rejected while the other accepted: {case.name} / {sample.id} / {stream_id}:\n"
                f"  interpreted: {left}\n  compiled: {right}"
            )
            continue

        assert left.error == right.error, (
            f"different exception classes: {case.name} / {sample.id} / {stream_id}:\n"
            f"  interpreted: {left}\n  compiled: {right}"
        )
        assert left.position == right.position, (
            f"different failure positions: {case.name} / {sample.id} / {stream_id}:\n"
            f"  interpreted: {left}\n  compiled: {right}"
        )
        if left.error == "EOFError":
            assert EOF_MESSAGE.match(left.message or ""), f"unexpected EOF message: {left.message!r}"
            assert EOF_MESSAGE.match(right.message or ""), f"unexpected EOF message: {right.message!r}"


@pytest.mark.parametrize("case", CASES)
@pytest.mark.parametrize("stream_id", STREAM_IDS)
def test_next_record_after_read(case: Case, stream_id: str) -> None:
    """After a read, both paths must leave the stream where the next record starts."""
    factory = STREAM_FACTORIES[stream_id]
    position_findings = []

    for sample in case.samples:
        if sample.start and not seekable(factory):
            continue

        interpreted, compiled = load_pair(case)

        streams = []
        for _ in range(2):
            stream = factory(sample.data)
            if sample.start:
                stream.seek(sample.start)
            streams.append(stream)

        first_left = observe(interpreted.test, streams[0], "interpreted", case.endian)
        first_right = observe(compiled.test, streams[1], "compiled", case.endian)

        aspects = divergences(first_left, first_right)
        if "position" in aspects or "consumed" in aspects or "status" in aspects:
            position_findings.append(Finding(case.name, sample, stream_id, aspects, first_left, first_right))
            continue

        second_left = observe(interpreted.next, streams[0], "interpreted", case.endian)
        second_right = observe(compiled.next, streams[1], "compiled", case.endian)

        assert second_left.ok == second_right.ok, (
            f"{case.name} / {sample.id} / {stream_id}: the next record parses differently:\n"
            f"  interpreted: {second_left}\n"
            f"  compiled:    {second_right}"
        )
        assert second_left.position == second_right.position
        if second_left.ok:
            assert same(second_left.value, second_right.value)

        # When exactly the marker record remains after the first read, the next read must return it
        # intact through both paths. That proves neither path skipped or duplicated bytes at the
        # record boundary.
        if stream_id in FULL_PARSE_STREAMS and first_left.ok and sample.data[first_left.position :] == NEXT_RECORD:
            assert second_left.ok, (
                f"{case.name} / {sample.id} / {stream_id}: the marker record at the parse boundary "
                f"was not read: {second_left}"
            )
            assert second_right.ok
            assert second_left.value[1][0] == ("magic", ("int", NEXT_MAGIC))
            assert second_right.value[1][0] == ("magic", ("int", NEXT_MAGIC))

    if position_findings:
        guard(position_findings, severity="record boundary")


@pytest.mark.parametrize("case", CASES)
def test_independent_instances_are_isomorphic(case: Case) -> None:
    """Two separately loaded instances of the same definition must agree for both paths."""
    # Explicitly bypass the cache: this test is about two *independent* loads
    first_interpreted, first_compiled = load_pair_uncached(case)
    second_interpreted, second_compiled = load_pair_uncached(case)

    for sample in case.samples:
        for left_type, right_type, path in (
            (first_interpreted.test, second_interpreted.test, "interpreted"),
            (first_compiled.test, second_compiled.test, "compiled"),
        ):
            left = observe(left_type, io.BytesIO(sample.data), path, case.endian)
            right = observe(right_type, io.BytesIO(sample.data), path, case.endian)

            assert left.ok == right.ok, f"{case.name} / {sample.id}: {path} is not deterministic"
            if left.ok:
                assert same(left.value, right.value)
                assert left.position == right.position
                assert left.dumps == right.dumps
                assert same(left.dynamic_sizes, right.dynamic_sizes)
            else:
                assert left.error == right.error
                assert left.position == right.position
                assert left.message == right.message


def test_inventory_is_current() -> None:
    """Every entry of the golden inventory must still be observed with the same counts.

    This is the other half of the baseline. ``guard`` catches new divergence signatures; this test
    catches the opposite, a signature that has disappeared because the read paths were fixed (or a
    sample that stopped being generated). Both directions must be acknowledged explicitly.
    """
    observed: dict[tuple[str, str, str], dict[tuple[str, ...], int]] = {}

    for param in CASES:
        case = param.values[0]
        for stream_id in STREAM_IDS:
            for finding in findings_for(case, stream_id):
                counts = observed.setdefault(finding.key, {})
                counts[finding.aspects] = counts.get(finding.aspects, 0) + 1

    stale = {
        key: (dict(sorted(observed.get(key, {}).items())), DIVERGENCE_INVENTORY[key])
        for key in DIVERGENCE_INVENTORY
        if observed.get(key, {}) != DIVERGENCE_INVENTORY[key]
    }
    assert not stale, (
        "The golden divergence inventory is stale. A changed signature or count means the read "
        "paths changed; update DIVERGENCE_INVENTORY:\n"
        + "\n".join(f"  {key}: observed={obs} recorded={rec}" for key, (obs, rec) in stale.items())
    )

    unexpected = {key: counts for key, counts in observed.items() if key not in DIVERGENCE_INVENTORY}
    assert not unexpected, "Divergences were observed for keys that are not in DIVERGENCE_INVENTORY:\n" + "\n".join(
        f"  {key}: {counts}" for key, counts in unexpected.items()
    )


def test_harness_detects_evidence_and_boundary_drift(monkeypatch: pytest.MonkeyPatch) -> None:
    """Prove the comparison is not vacuous by injecting a drift into one of the two paths.

    A differential test that only ever says "no crash" would pass even if one path silently rewrote
    evidence or moved the record boundary. Here one path is deliberately made to return a different
    field value and consume one extra byte; the harness must report exactly those two aspects, and
    the resulting finding must not be tolerated by the catalogue.
    """
    definition = "struct test { uint32 a; uint32 b; };"
    interpreted = cstruct().load(definition, compiled=False).test
    compiled = cstruct().load(definition).test
    original = compiled._read.__func__

    def drifted(cls: Any, stream: Any, *, context: Any = None, endian: str) -> Any:
        obj = original(cls, stream, context=context, endian=endian)
        stream.read(1)
        obj.a = 0
        return obj

    monkeypatch.setattr(compiled, "_read", classmethod(drifted))

    # One byte of trailing data, so the extra read by the drifted path is actually observable
    data = bytes(range(9))
    left = observe(interpreted, io.BytesIO(data), "interpreted", "<")
    right = observe(compiled, io.BytesIO(data), "compiled", "<")

    assert left.ok
    assert right.ok

    # The injected drift must surface as a changed field value, a changed boundary and changed bytes
    assert divergences(left, right) == ("consumed", "dumps", "value")
    assert left.consumed == 8
    assert right.consumed == 9

    finding = Finding(
        "injected", Sample("legal/drift", data, legal=True), "seekable", ("consumed", "dumps", "value"), left, right
    )
    assert finding.key not in DIVERGENCE_INVENTORY, "the catalogue must not tolerate an injected drift"


